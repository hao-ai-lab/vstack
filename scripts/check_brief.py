#!/usr/bin/env python3
"""Check a task brief generated from templates/task-brief.md (or a domain template) before it is sent. Read-only."""

import argparse
import hashlib
import re
import sys
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parent.parent
TEMPLATE = ROOT / "templates" / "task-brief.md"
DOMAIN_DIR = "briefs"

HEADING = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
FENCE = re.compile(r"^\s*(```|~~~)")
COMMENT = re.compile(r"<!--.*?-->", re.S)
CODE_SPAN = re.compile(r"(`+)(.+?)\1")
ITEM = re.compile(r"^\s*(?:[-*+]|\d+[.)])\s+(.*)$")
LEAD = r"^\s*(?:(?:[-*+]|\d+[.)])\s+)?"
FIELD = re.compile(LEAD + r"(command|last line ends with|last line matches|last line):\s*(.*?)\s*$", re.I)
MODES = {"last line": "exact", "last line ends with": "suffix", "last line matches": "regex"}
FINDINGS = re.compile(r"finding[- ]records?\b", re.I)
GRADER = re.compile(r"grade_findings\.py|gate grade-findings")
BLIND = re.compile(LEAD + r"blind:\s*(\S+)", re.I | re.M)
EXCEPT = re.compile(r"^except\s+(.*)$", re.I)
AUTOLINK = re.compile(r"^(?:[A-Za-z][A-Za-z0-9+.-]*:\S+|[^\s@]+@[^\s@]+)$")
HTML_TAG = re.compile(r"^/?(?:b|i|p|br|em|hr|pre|sub|sup|kbd|code|strong|details|summary)\s*/?$", re.I)
ANGLE = re.compile(r"<([A-Za-z.][^<>\n\"=]{0,239})>")
MARKERS = [re.compile(r"\b__[A-Z][A-Z0-9_]*__\b"), re.compile(r"\{\{[^{}\n]*\}\}"),
           re.compile(r"\b(?:TODO|TBD|FIXME)\b"),
           re.compile(r"<[a-z][a-z0-9 -]*:(?![^<>\n]*>)[^\n]*")]  # a slot opened and not closed on its line
KEYWORDS = {"TODO", "TBD", "FIXME"}
SLOT = re.compile(r"<([a-z][a-z0-9 -]*)(?::[^<>\n]*)?>")
SPANS = r"((?:`[^`\n]+`\s*(?:,\s*|\s+and\s+)?)+)"
LITERAL = re.compile(LEAD + r"literal:\s*" + SPANS, re.I)
IDS = re.compile(LEAD + r"ids:\s*`([^`\n]+)`\s+(?:from\s+`([^`\n]+)`\s+column\s+`([^`\n]+)`|only\s+" + SPANS + ")",
                 re.I)
REF = re.compile(LEAD + r"ref:\s*`([^`\n]+)`\s+column\s+`([^`\n]+)`\s*->\s*`([^`\n]+)`\s+column\s+`([^`\n]+)`", re.I)
DECLARATION = re.compile(LEAD + r"(?:literal|ids|ref):", re.I)
COUNT = re.compile(r"\b(\d+)\s+rows\s+of\s+(`[^`\n]+`(?:\s*(?:,|,?\s+and)\s+`[^`\n]+`)*)(?:\s+where\s+`([^`\n]+)`)?")
BARE_COUNT = re.compile(r"\b(\d+)\s+(?:[A-Za-z-]+\s+){0,2}rows?\b")
HEADER_OF = re.compile(r"header\s+`([^`\n]+)`\s+\(from\s+`([^`\n]+)`\)")
PATH_TOKEN = re.compile(r"(?<![\w.~/:-])/[^\s`'\"<>()|;,]+")
STAMP = re.compile(r"^<!-- generated by make_brief\.py: template (.+?) sha256 ([0-9a-f]{64}); fields (.+?) sha256 "
                   r"([0-9a-f]{64}); body sha256 ([0-9a-f]{64})\. .*-->$")
CONDITION = re.compile(r"^\s*([^=!\s][^=!]*?)\s*(!=|=)\s*(.*?)\s*$")
FAILING_LINES = ("", "FAIL", "ERROR")
MASK = "\ue000"


class Parser(argparse.ArgumentParser):
    def error(self, message):
        self.exit(2, f"ERROR arguments: {message}\n")


class Rules:
    """What the template defines: the sections in order, the hand-back fields and every slot text."""

    def __init__(self, path, sections, fields, slots):
        self.path, self.sections, self.fields, self.slots = path, sections, fields, slots


class Writable:
    """Writable paths of a brief: absolute paths or globs, minus `except` items."""

    def __init__(self, includes=(), excludes=()):
        self.includes, self.excludes = list(includes), list(excludes)

    def allows(self, path):
        path = str(path)
        return (any(covers(item, path) for item in self.includes)
                and not any(covers(item, path) for item in self.excludes))

    def roots(self):
        """Plain (non-glob) include paths, in order."""
        return [item for item in self.includes if not is_glob(item)]


class Brief:
    def __init__(self, name):
        self.name, self.errors = name, []
        self.sections, self.done, self.writable, self.blind = {}, [], Writable(), None
        self.blind_paths, self.counts, self.ids, self.refs, self.literals = [], [], [], [], []
        self.stamp, self.readable = None, True

    def error(self, where, reason):
        self.errors.append(f"ERROR {self.name}{':' + str(where) if where else ''}: {reason}")


def strip_comments(text):
    """Blank out HTML comments, keeping line numbers."""
    return COMMENT.sub(lambda m: "\n" * m.group(0).count("\n"), text)


def read_template(path):
    """Return the sections (## headings), hand-back fields and slot texts of one brief template."""
    text = strip_comments(Path(path).read_text(encoding="utf-8"))
    sections, fields, fence, block = [], [], False, False
    for line in text.split("\n"):
        stripped = line.strip()
        if stripped == "BEGIN HANDBACK":
            block = True
            continue
        if stripped == "END HANDBACK":
            block = False
            continue
        if block:
            field = re.match(r"^([a-z][a-z ]*[a-z]):", stripped)
            if field and field.group(1) not in fields:
                fields.append(field.group(1))
            continue
        if FENCE.match(line):
            fence = not fence
            continue
        heading = None if fence else HEADING.match(line)
        if heading and len(heading.group(1)) == 2:
            sections.append(heading.group(2).strip())
    if not sections or not fields:
        raise ValueError(f"{path}: no '##' sections or no hand-back block fields")
    return sections, fields, {match.group(0) for match in SLOT.finditer(text)}


def load_rules(template=None):
    """Rules from the base template; slot texts also from the domain templates next to it."""
    path = Path(template or TEMPLATE)
    sections, fields, slots = read_template(path)
    for domain in sorted((path.parent / DOMAIN_DIR).glob("*.md")):
        slots |= {match.group(0) for match in SLOT.finditer(strip_comments(domain.read_text(encoding="utf-8")))}
    return Rules(path, sections, fields, slots)


def unquote(value):
    """Return the content of a value written as one code span, else the value itself."""
    value = value.strip()
    match = re.fullmatch(r"(`+)\s*(.*?)\s*\1", value)
    return match.group(2) if match else value


def first_token(text):
    text = text.strip()
    match = re.match(r"(`+)\s*(.*?)\s*\1", text)
    if match:
        return match.group(2)
    return text.split()[0].rstrip(":;,") if text.split() else ""


def spans_of(text):
    return re.findall(r"`([^`\n]+)`", text)


def is_glob(item):
    return any(char in item for char in "*?")


def glob_regex(pattern):
    out, index = "", 0
    while index < len(pattern):
        if pattern.startswith("**", index):
            out, index = out + ".*", index + 2
        elif pattern[index] == "*":
            out, index = out + "[^/]*", index + 1
        elif pattern[index] == "?":
            out, index = out + "[^/]", index + 1
        else:
            out, index = out + re.escape(pattern[index]), index + 1
    return re.compile(out)


def covers(item, path):
    """True when path is item, lies under item, or (for a glob) it or one of its parents matches the glob."""
    item, path = str(item).rstrip("/") or "/", str(path).rstrip("/") or "/"
    if not is_glob(item):
        return path == item or path.startswith(item + "/") or item == "/"
    regex, probe = glob_regex(item), PurePosixPath(path)
    return any(regex.fullmatch(str(candidate)) for candidate in [probe, *probe.parents])


def tsv_lines(path):
    """Non-blank, non-# lines of a TSV file; the first is its header."""
    lines = [line for line in Path(path).read_text(encoding="utf-8").splitlines()
             if line.strip() and not line.lstrip().startswith("#")]
    if not lines:
        raise ValueError(f"{path} has no header line")
    return lines


def parse_conditions(text):
    conditions = []
    for part in re.split(r"\s+and\s+", text.strip()) if text and text.strip() else []:
        match = CONDITION.match(part)
        if not match:
            raise ValueError(f"condition {part!r} is not COLUMN=VALUE or COLUMN!=VALUE")
        conditions.append((match.group(1), match.group(2), match.group(3)))
    return conditions


def count_rows(paths, conditions=()):
    """Data rows of each TSV file, each file's own header skipped, blank and # lines ignored, filtered."""
    total = 0
    for path in paths:
        lines = tsv_lines(path)
        header = lines[0].split("\t")
        checks = []
        for column, op, value in conditions:
            if column not in header:
                raise ValueError(f"{path} has no column {column!r}")
            checks.append((header.index(column), op, value))
        for line in lines[1:]:
            cells = line.split("\t")
            total += all(((cells[i].strip() if i < len(cells) else "") == value) == (op == "=")
                         for i, op, value in checks)
    return total


def column_values(path, column):
    """Values of one column of a TSV; cells are split on ';', ',' and whitespace."""
    lines = tsv_lines(path)
    header = lines[0].split("\t")
    if column not in header:
        raise ValueError(f"{path} has no column {column!r}")
    index, values = header.index(column), set()
    for line in lines[1:]:
        cells = line.split("\t")
        if index < len(cells):
            values |= {value for value in re.split(r"[;,\s]+", cells[index].strip()) if value}
    return values


def template_header(name):
    path = Path(name) if name.startswith("/") else ROOT / name
    return tsv_lines(path)[0]


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def stamp_of(raw, brief, provenance):
    """Find and verify the generator's stamp; return its line index or None."""
    lines = raw.split("\n")
    found = [(index, match) for index, line in enumerate(lines) if (match := STAMP.match(line.strip()))]
    if len(found) > 1:
        brief.error(found[1][0] + 1, "more than one generator stamp")
    if not found:
        return None
    index, match = found[0]
    body = "\n".join(lines[:index] + lines[index + 1:])
    template, template_hash, fields, fields_hash, body_hash = match.groups()
    brief.stamp = {"template": template, "fields": fields}
    if hashlib.sha256(body.encode("utf-8")).hexdigest() != body_hash:
        brief.error(index + 1, "the brief was edited after it was generated (its text no longer matches the "
                               "stamp); change the fields file and run scripts/make_brief.py again")
    if provenance:
        for label, path, expected in (("template", template, template_hash), ("fields file", fields, fields_hash)):
            try:
                if sha256(path) != expected:
                    brief.error(index + 1, f"the {label} {path} changed since this brief was generated; regenerate "
                                           "it (a changed template starts a new batch)")
            except OSError as exc:
                brief.error(index + 1, f"cannot read the {label} {path} named by the stamp: {exc.strerror or exc}")
    return index


def declarations(lines, brief):
    """Parse literal, ids and ref declarations (outside fences)."""
    fence = False
    for no, line in enumerate(lines, 1):
        if FENCE.match(line):
            fence = not fence
            continue
        if fence or not DECLARATION.match(line):
            continue
        if match := LITERAL.match(line):
            for value in spans_of(match.group(1)):
                if value.strip() in KEYWORDS or any(slot in value for slot in brief.rules.slots):
                    brief.error(no, f"literal {value!r} would hide a placeholder; declare the exact marker text")
                else:
                    brief.literals.append(value)
        elif match := IDS.match(line):
            pattern, path, column, inline = match.groups()
            try:
                regex = re.compile(pattern)
            except re.error as exc:
                brief.error(no, f"ids pattern {pattern!r} is not a regular expression: {exc}")
                continue
            if regex.fullmatch(""):
                brief.error(no, f"ids pattern {pattern!r} matches the empty string")
                continue
            if inline is not None:
                values, source = set(spans_of(inline)), "the ids listed at line " + str(no)
            elif not path.startswith("/"):
                brief.error(no, f"ids table must be an absolute path: {path}")
                continue
            else:
                try:
                    values, source = column_values(path, column), f"{path} column {column}"
                except (OSError, UnicodeError, ValueError) as exc:
                    brief.error(no, f"cannot read ids from {path}: {getattr(exc, 'strerror', None) or exc}")
                    continue
            brief.ids.append((no, regex, values, source))
        elif match := REF.match(line):
            out, column, table, id_column = match.groups()
            if not table.startswith("/"):
                brief.error(no, f"ref table must be an absolute path: {table}")
                continue
            try:
                column_values(table, id_column)
            except (OSError, UnicodeError, ValueError) as exc:
                brief.error(no, f"ref table {table}: {getattr(exc, 'strerror', None) or exc}")
                continue
            brief.refs.append((no, out, column, table, id_column))
        else:
            brief.error(no, "declaration not understood; the forms are 'literal: `TEXT`', "
                            "'ids: `REGEX` from `FILE` column `NAME`', 'ids: `REGEX` only `ID`, `ID`' and "
                            "'ref: `OUTPUT` column `NAME` -> `TABLE` column `NAME`'")


def scan_placeholders(lines, brief):
    fence = False
    for no, line in enumerate(lines, 1):
        if FENCE.match(line):
            fence = not fence
            continue
        found = {}
        for slot in brief.rules.slots:
            start = line.find(slot)
            while start != -1:
                found.setdefault(start, slot)
                start = line.find(slot, start + 1)
        for pattern in MARKERS:
            for match in pattern.finditer(line):
                found.setdefault(match.start(), match.group(0))
        field = None if fence else FIELD.match(line)
        value_start = field.start(2) if field else len(line) + 1
        regex_value = bool(field) and MODES.get(field.group(1).lower()) == "regex"
        code = [(m.start(), m.end()) for m in CODE_SPAN.finditer(line)]
        for match in ANGLE.finditer(line):
            inner, start = match.group(1), match.start()
            if HTML_TAG.match(inner) or AUTOLINK.match(inner):
                continue
            if start >= value_start:
                if regex_value:
                    continue  # a pattern's named groups are not placeholders
            elif (fence or any(a <= start < b for a, b in code)) and not re.search(r"\s", inner):
                continue  # usage syntax in code, such as `slides/<id>.html` or `<file>`
            found.setdefault(start, match.group(0))
        for start in sorted(found):
            brief.error(no, f"placeholder left: {found[start]}")


def check_counts(lines, brief):
    text, fence, rows = [], False, []
    for line in lines:
        if FENCE.match(line):
            fence = not fence
            text.append("")
        else:
            text.append("" if fence else line)
    joined = "\n".join(text)
    flat = joined.replace("\n", " ")
    covered = []
    for match in COUNT.finditer(flat):
        no = joined.count("\n", 0, match.start()) + 1
        covered.append(match.start())
        files, claimed = spans_of(match.group(2)), int(match.group(1))
        relative = [path for path in files if not path.startswith("/")]
        if relative:
            brief.error(no, f"a counted file must be an absolute path: {relative[0]}")
            continue
        try:
            actual = count_rows(files, parse_conditions(match.group(3)))
        except (OSError, UnicodeError, ValueError) as exc:
            brief.error(no, f"cannot recount '{match.group(0)}': {getattr(exc, 'strerror', None) or exc}")
            continue
        brief.counts.append((no, claimed, files))
        if actual != claimed:
            brief.error(no, f"the brief says {claimed} rows of {', '.join(files)}"
                            f"{' where ' + match.group(3) if match.group(3) else ''}; the files hold {actual} "
                            "(each file's own header skipped)")
    masked = CODE_SPAN.sub(lambda m: " " * len(m.group(0)), flat)
    for match in BARE_COUNT.finditer(masked):
        if match.start() not in covered:
            no = joined.count("\n", 0, match.start()) + 1
            brief.error(no, f"row count '{match.group(0)}' is not tied to its files; write it as "
                            "'N rows of `FILE`' so that it can be recounted (make_brief.py computes it from "
                            "'{{rows of FILE}}'), or, for rows that are not data rows of a TSV file, declare the "
                            "phrase with 'literal: `TEXT`'")


def check_ids(lines, brief):
    """Every match of an 'ids:' pattern must be a listed id (of that declaration or another that matches it)."""
    for no, line in enumerate(lines, 1):
        if DECLARATION.match(line):
            continue
        seen = set()
        for _, regex, values, source in brief.ids:
            for match in regex.finditer(line):
                value = match.group(0)
                if value in seen:
                    continue
                seen.add(value)
                if value in values or any(value in other_values for _, other, other_values, _ in brief.ids
                                          if other.fullmatch(value)):
                    continue
                brief.error(no, f"id {value} is not in {source} (text left from another brief?)")


def check_text(raw, name, rules=None, provenance=False):
    """Check the text of a brief; return a Brief with its parts and errors."""
    brief = Brief(name)
    brief.rules = rules or load_rules()
    stamp_line = stamp_of(raw, brief, provenance)
    lines = strip_comments(raw).split("\n")
    if stamp_line is not None:
        lines[stamp_line] = ""
    declarations(lines, brief)
    masked = list(lines)
    for literal in sorted(brief.literals, key=len, reverse=True):
        masked = [line.replace(literal, MASK * len(literal)) for line in masked]
    scan_placeholders(masked, brief)
    check_counts(masked, brief)
    check_ids(masked, brief)

    found, order, fence, current = {}, [], False, None
    for no, line in enumerate(lines, 1):
        if FENCE.match(line):
            fence = not fence
        heading = None if fence else HEADING.match(line)
        if heading and len(heading.group(1)) <= 2:
            current = None
            title = heading.group(2).strip()
            if len(heading.group(1)) == 2 and title in brief.rules.sections:
                if title in found:
                    brief.error(no, f"section '{title}' appears twice")
                    continue
                current = title
                found[title] = (no, [])
                order.append(title)
            continue
        if current:
            found[current][1].append((no, line))
    for title in brief.rules.sections:
        if title not in found:
            brief.error(None, f"missing section '## {title}'")
    present = [title for title in brief.rules.sections if title in found]
    if order != present:
        brief.error(None, "sections out of order; expected " + ", ".join(present))
    for title, (start, body) in found.items():
        text = "\n".join(line for _, line in body)
        brief.sections[title] = (start, text, body)
        if not text.strip():
            brief.error(start, f"section '{title}' is empty")
    sections = brief.sections

    if "Writable paths" in sections:
        start, text, body = sections["Writable paths"]
        items = [(no, item.group(1)) for no, line in body if (item := ITEM.match(line))]
        includes, excludes = [], []
        for no, item in items:
            excluded = EXCEPT.match(item)
            token = first_token(excluded.group(1) if excluded else item)
            if not token.startswith("/") or token == "/":
                brief.error(no, f"writable path must be absolute: {token or item}")
            elif ".." in PurePosixPath(token).parts or "//" in token:
                brief.error(no, f"writable path must be canonical: {token}")
            else:
                (excludes if excluded else includes).append((no, token))
        for no, token in excludes:
            if not any(covers(item, token.split("*")[0].split("?")[0]) for _, item in includes):
                brief.error(no, f"'except {token}' lies under no writable path")
        brief.writable = Writable([t for _, t in includes], [t for _, t in excludes])
        if not includes and not items and text.strip():
            brief.error(start, "no writable path listed as a list item")

    if "Forbidden paths and actions" in sections:
        start, text, body = sections["Forbidden paths and actions"]
        values = BLIND.findall(text)
        if len(values) != 1 or values[0].lower().rstrip(".") not in {"yes", "no"}:
            brief.error(start, "forbidden section needs exactly one line 'Blind: yes' or 'Blind: no'")
        else:
            brief.blind = values[0].lower().rstrip(".") == "yes"
            if brief.blind:
                brief.blind_paths = [(no, token) for no, line in body if (m := ITEM.match(line))
                                     and not BLIND.match(line) and (token := first_token(m.group(1))).startswith("/")]
                if not brief.blind_paths:
                    brief.error(start, "Blind: yes needs a list item naming each absolute path the worker must not "
                                       "open")
        if brief.blind:
            reported = set()
            for title, (_, _, body) in sections.items():
                if title == "Forbidden paths and actions":
                    continue
                for no, line in body:
                    for token in PATH_TOKEN.findall(line):
                        token = token.rstrip(".,:;")
                        if len(token) < 2 or token.startswith("//"):
                            continue
                        for blind_no, blind in brief.blind_paths:
                            if covers(blind, token) and (blind, token) not in reported:
                                reported.add((blind, token))
                                brief.error(blind_no, f"blind path {blind} contains {token}, which section "
                                                      f"'{title}' (line {no}) gives the worker; narrow the blind "
                                                      "path or drop that path")

    if "What to produce" in sections:
        start, text, _ = sections["What to produce"]
        if text.strip() and "as you go" not in text.lower():
            brief.error(start, "say that output files are written as you go, so that a partial result is usable")

    if "Done evidence" in sections:
        start, _, body = sections["Done evidence"]
        pending = None
        for no, line in body:
            field = FIELD.match(line)
            if not field:
                continue
            key, value = field.group(1).lower(), unquote(field.group(2))
            if key == "command":
                if pending:
                    brief.error(pending[0], f"command has no expected last line: {pending[1]}")
                pending = (no, value)
                if not value:
                    brief.error(no, "empty command")
                continue
            if not pending:
                brief.error(no, f"'{key}:' without a preceding 'command:'")
                continue
            mode = MODES[key]
            if not value:
                brief.error(no, "empty expected last line")
            elif mode == "regex":
                try:
                    regex = re.compile(value)
                except re.error as exc:
                    brief.error(no, f"'last line matches:' needs a regular expression: {exc}")
                else:
                    accepted = [line for line in FAILING_LINES if regex.fullmatch(line)]
                    if accepted:
                        brief.error(no, f"pattern {value!r} accepts the line {accepted[0]!r}, so a failed or "
                                        "empty run would count as done")
            elif value[-1] in "=:":
                brief.error(no, f"expected last line {value!r} ends with '{value[-1]}', so a real line carries a "
                                "value after it and never matches; use 'last line matches:' with a pattern for "
                                "the value")
            brief.done.append((pending[0], pending[1], mode, value))
            pending = None
        if pending:
            brief.error(pending[0], f"command has no expected last line: {pending[1]}")
        if not brief.done:
            brief.error(start, "done evidence names no command ('command:' followed by 'last line:')")
        produce = sections.get("What to produce", (0, ""))[1]
        if FINDINGS.search(produce) and not any(GRADER.search(command) for _, command, _, _ in brief.done):
            brief.error(start, "the outputs include finding records: the done evidence must run "
                               "scripts/grade_findings.py on them and expect it to pass")

    if "Hand-back" in sections:
        start, text, _ = sections["Hand-back"]
        lowered = text.lower()
        missing = [name for name in ["BEGIN HANDBACK", "END HANDBACK"] if name not in text]
        missing += [f"{name}:" for name in brief.rules.fields if f"{name}:" not in lowered]
        if text.strip() and missing:
            brief.error(start, "hand-back section must carry the hand-back block; missing " + ", ".join(missing))

    for no, line in enumerate(lines, 1):
        for match in HEADER_OF.finditer(line):
            stated, source = match.groups()
            try:
                actual = template_header(source)
            except (OSError, UnicodeError, ValueError) as exc:
                brief.error(no, f"cannot read the header of {source}: {getattr(exc, 'strerror', None) or exc}")
                continue
            if stated != actual:
                brief.error(no, f"the header given for {source} differs from that template's header: "
                                f"{actual.replace(chr(9), ' | ')}")

    for no, out, _, _, _ in brief.refs:
        if out.startswith("/") and not brief.writable.allows(out):
            brief.error(no, f"ref output {out} lies outside the writable paths")
    return brief


def parse_brief(path, rules=None, provenance=False):
    """Read and check a brief file; return a Brief."""
    try:
        raw = Path(path).read_text(encoding="utf-8")
    except (OSError, UnicodeError) as exc:
        brief = Brief(str(path))
        brief.readable = False
        brief.error(None, str(exc))
        return brief
    return check_text(raw, str(path), rules, provenance)


def main():
    parser = Parser(description=__doc__, epilog=(
        "Sections and hand-back fields come from the template (--template, default templates/task-brief.md), and "
        "the slots of that template and of templates/briefs/*.md count as placeholders. Fails when: the brief "
        "lacks the generator's stamp (unless --hand-written) or was edited after generation, or its template or "
        "fields file changed since; a section is missing, out of order or empty (HTML comments do not count); a "
        "placeholder is left: a template slot anywhere, __NAME__, {{...}}, TODO, TBD or FIXME anywhere, <...> in "
        "prose or in a done-evidence command or exact or suffix line, or <...> holding a space in code (a "
        "one-word <file> in code is usage syntax); text declared with 'literal: `TEXT`' is exempt; a writable "
        "path is not absolute and canonical (globs * ** ? and 'except PATH' items allowed); 'Blind: yes|no' is "
        "absent, a blind brief lists no path, or a blind path contains a path another section gives the worker; "
        "the outputs are not written as you go; the done evidence names no 'command:' with 'last line:', "
        "'last line ends with:' or 'last line matches:' (a regular expression for the whole line), an exact or "
        "suffix line ends with '=' or ':', or a pattern accepts an empty, FAIL or ERROR line; outputs that "
        "include finding records are not graded by scripts/grade_findings.py; the hand-back section lacks the "
        "block; 'N rows of `FILE`...[ where `COL=VALUE`]' differs from the files (each file's own header "
        "skipped) or a row count in prose is not tied to files; an id matching an 'ids:' declaration is not in "
        "its table or list; a 'ref:' table or column is missing; a 'header `...` (from `TEMPLATE`)' differs "
        "from that template. It checks form and stated facts, not whether the brief is right. "
        "Exit 0: valid; 1: invalid or unreadable; 2: usage."))
    parser.add_argument("brief", type=Path, metavar="BRIEF.md")
    parser.add_argument("--template", type=Path, metavar="FILE", help="template defining sections and fields")
    parser.add_argument("--hand-written", action="store_true",
                        help="accept a brief without the stamp of scripts/make_brief.py (the OK line says so)")
    args = parser.parse_args()
    try:
        rules = load_rules(args.template)
    except (OSError, UnicodeError, ValueError) as exc:
        print(f"ERROR template: {exc}\nFAIL brief: 1 errors")
        return 1
    brief = parse_brief(args.brief, rules, provenance=True)
    if brief.stamp is None and not args.hand_written and brief.readable:
        brief.error(None, "not generated from a template: write a fields file and run scripts/make_brief.py "
                          "(or pass --hand-written)")
    for message in brief.errors:
        print(message)
    if brief.errors:
        print(f"FAIL brief: {len(brief.errors)} errors")
        return 1
    print(f"OK brief: {len(brief.sections)} sections, {len(brief.writable.includes)} writable paths, "
          f"{len(brief.done)} done checks, blind={'yes' if brief.blind else 'no'}, {len(brief.counts)} counts, "
          f"{len(brief.ids)} id sets, {len(brief.refs)} refs, generated={'yes' if brief.stamp else 'no'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
